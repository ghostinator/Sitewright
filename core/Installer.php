<?php
declare(strict_types=1);

namespace Sitewright\Core;

/** CLI installer logic (bin/install.php). There is no web installer. */
final class Installer
{
    public static function configPath(): string { return Config::root() . '/config/config.php'; }
    public static function lockPath(): string { return Config::root() . '/storage/install.lock'; }

    /** @return array{host:string,port:int,name:string,user:string,pass:string,prefix:string} */
    public static function validateDb(array $in): array
    {
        $host = (string)($in['host'] ?? '127.0.0.1');
        $port = (string)($in['port'] ?? '3306');
        $name = (string)($in['name'] ?? '');
        $user = (string)($in['user'] ?? '');
        $pass = (string)($in['pass'] ?? '');
        $prefix = (string)($in['prefix'] ?? 'sw_');

        $hostOk = preg_match('/^[A-Za-z0-9]([A-Za-z0-9.\-]{0,251}[A-Za-z0-9])?$/D', $host) || filter_var($host, FILTER_VALIDATE_IP, FILTER_FLAG_IPV6);
        if (!$hostOk) { throw new \InvalidArgumentException('Invalid database host'); }
        if (!preg_match('/^[0-9]{1,5}$/D', $port) || (int)$port < 1 || (int)$port > 65535) { throw new \InvalidArgumentException('Invalid database port (1-65535)'); }
        if (!preg_match('/^[A-Za-z0-9_]{1,64}$/D', $name)) { throw new \InvalidArgumentException('Invalid database name (letters, digits, underscore; max 64)'); }
        if ($user === '' || strlen($user) > 80 || preg_match('/[\x00-\x1F\x7F]/', $user)) { throw new \InvalidArgumentException('Invalid database user'); }
        if (strlen($pass) > 255 || str_contains($pass, "\0")) { throw new \InvalidArgumentException('Invalid database password'); }
        if (!preg_match('/^[A-Za-z0-9_]{0,16}$/D', $prefix)) { throw new \InvalidArgumentException('Invalid table prefix (letters, digits, underscore; max 16)'); }
        return ['host' => $host, 'port' => (int)$port, 'name' => $name, 'user' => $user, 'pass' => $pass, 'prefix' => $prefix];
    }

    /** @return array{username:string,email:string,password:string} */
    public static function validateAdmin(array $in): array
    {
        $u = (string)($in['username'] ?? ''); $e = (string)($in['email'] ?? ''); $p = (string)($in['password'] ?? '');
        if (!preg_match('/^[A-Za-z0-9_.\-]{3,60}$/D', $u)) { throw new \InvalidArgumentException('Admin username: 3-60 chars of letters, digits, . _ -'); }
        if (!filter_var($e, FILTER_VALIDATE_EMAIL) || strlen($e) > 100) { throw new \InvalidArgumentException('Invalid admin email'); }
        if (strlen($p) < 12 || strlen($p) > 1024) { throw new \InvalidArgumentException('Admin password must be 12-1024 characters'); }
        return ['username' => $u, 'email' => $e, 'password' => $p];
    }

    /** PHP source for config/config.php. Values go through var_export(): nothing is ever interpolated as code. */
    public static function renderConfig(array $db): string
    {
        $export = var_export(['db' => [
            'host' => $db['host'], 'port' => (int)$db['port'], 'name' => $db['name'], 'user' => $db['user'], 'pass' => $db['pass'], 'prefix' => $db['prefix'],
        ]], true);
        return "<?php\n// Generated by bin/install.php. Keep this file private (chmod 0600). See config.example.php for all options.\nreturn $export;\n";
    }

    /**
     * @param array{db:array,admin:array,create_db?:bool,config_path?:string,lock_path?:string} $o
     * @return array{applied:string[],config:string}
     */
    public static function run(array $o): array
    {
        $configPath = $o['config_path'] ?? self::configPath();
        $lockPath = $o['lock_path'] ?? self::lockPath();
        if (file_exists($configPath) || file_exists($lockPath)) {
            throw new \RuntimeException('Already installed (config or lock file exists). Use bin/migrate.php to upgrade; delete both files only if you really intend to reinstall.');
        }
        $db = self::validateDb($o['db']);
        $admin = self::validateAdmin($o['admin']);

        if (!empty($o['create_db'])) {
            $pdo = Database::connect($db, false);
            $pdo->exec('CREATE DATABASE IF NOT EXISTS `' . $db['name'] . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
        }
        $pdo = Database::connect($db);
        $applied = (new Migrator($pdo, $db['prefix']))->run();

        $users = '`' . $db['prefix'] . 'users`';
        $st = $pdo->prepare("INSERT INTO $users (username, email, password, display_name) VALUES (?, ?, ?, ?)");
        $st->execute([$admin['username'], $admin['email'], password_hash($admin['password'], PASSWORD_DEFAULT), $admin['username']]);

        $fh = fopen($configPath, 'x');
        if ($fh === false) { throw new \RuntimeException('Could not create config file'); }
        chmod($configPath, 0600);
        fwrite($fh, self::renderConfig($db));
        fclose($fh);
        file_put_contents($lockPath, 'installed ' . gmdate('c') . "\n");
        @chmod($lockPath, 0600);
        return ['applied' => $applied, 'config' => $configPath];
    }
}
